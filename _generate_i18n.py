def apply_common_path_fixes(html: str) -> str:
    for old, new in ASSET_FIXES:
        html = html.replace(old, new)
    return html


def replace_once(html: str, old: str, new: str, required: bool = True) -> str:
    if old not in html:
        if required:
            raise SystemExit(f"Missing string to replace:\n{old[:120]}")
        return html
    return html.replace(old, new, 1)


